"""Write docs/code-map.md: one line per module, so a session can find code without searching.

Each line is the path and the module's own first comment line. A module without one lists its
public names (Python and TypeScript) or the components it uses (Svelte). `--check` fails when the
file is out of date; it passes when docs/ is absent (docs/ is private, not in a fresh clone).
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "code-map.md"
ROOTS = (ROOT / "src" / "scrolly", ROOT / "frontend" / "src", ROOT / "scripts")
SKIP = {"api-types.ts", "versions", "__pycache__", "static", "node_modules"}
NAMES_SHOWN = 6

BLOCK_COMMENT = re.compile(r"^\s*/\*+(.*?)\*/", re.DOTALL)
HTML_COMMENT = re.compile(r"<!--(.*?)-->", re.DOTALL)
EXPORTED = re.compile(
    r"^export\s+(?:async\s+)?(?:function|const|class|type|interface)\s+(\w+)", re.MULTILINE
)
IMPORTED_COMPONENT = re.compile(r"import\s+(\w+)\s+from\s+'[^']*\.svelte'")


def first_line(text: str) -> str:
    for line in text.splitlines():
        line = line.strip(" */#\t")
        if line:
            return line
    return ""


def python_summary(source: str) -> str:
    tree = ast.parse(source)
    doc = ast.get_docstring(tree)
    if doc:
        return first_line(doc)
    names = [
        node.name
        for node in tree.body
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
        and not node.name.startswith("_")
    ]
    return names_text(names)


def typescript_summary(source: str) -> str:
    block = BLOCK_COMMENT.match(source)
    if block:
        return first_line(block.group(1))
    leading = [line for line in source.splitlines()[:3] if line.startswith("//")]
    if leading:
        return first_line(leading[0])
    return names_text(EXPORTED.findall(source))


def svelte_summary(source: str) -> str:
    comment = HTML_COMMENT.search(source)
    if comment:
        return first_line(comment.group(1))
    return names_text(IMPORTED_COMPONENT.findall(source), prefix="uses")


def names_text(names: list[str], prefix: str = "") -> str:
    if not names:
        return ""
    shown = ", ".join(names[:NAMES_SHOWN]) + (" …" if len(names) > NAMES_SHOWN else "")
    return f"{prefix} {shown}".strip()


def summary(path: Path) -> str:
    source = path.read_text(encoding="utf-8")
    if path.suffix == ".py":
        return python_summary(source)
    if path.suffix == ".svelte":
        return svelte_summary(source)
    return typescript_summary(source)


def modules() -> list[Path]:
    found = [
        path
        for root in ROOTS
        for suffix in ("*.py", "*.ts", "*.svelte")
        for path in root.rglob(suffix)
        if not SKIP.intersection(path.relative_to(ROOT).parts) and path.name != "__init__.py"
    ]
    return sorted(found, key=lambda path: path.relative_to(ROOT).as_posix())


def build_map() -> str:
    lines = [
        "# Code map",
        "",
        "Generated by `uv run poe map`; do not edit. One line per module: its own first comment",
        "line, or its public names (`uses` = components it renders). Read this before searching.",
    ]
    folder = None
    for path in modules():
        relative = path.relative_to(ROOT)
        if relative.parent != folder:
            folder = relative.parent
            lines += ["", f"## {folder.as_posix()}/", ""]
        note = summary(path)
        lines.append(f"- `{relative.name}`" + (f" — {note}" if note else ""))
    return "\n".join(lines) + "\n"


def main() -> int:
    if "--check" in sys.argv:
        if not OUT.parent.exists():
            print("docs/ is absent: code map not checked.")
            return 0
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != build_map():
            print("docs/code-map.md is out of date. Run: uv run poe map")
            return 1
        print("docs/code-map.md is up to date.")
        return 0
    OUT.write_text(build_map(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
